export function generateASCIIArt(text: string, style: 'block' | 'simple' | 'bold' | 'big' = 'block'): string {
  const upperText = text.toUpperCase()
  const chars = upperText.split('')
  
  // Select font based on style
  const font = style === 'big' ? bigFont : blockFont
  const height = style === 'big' ? 7 : 5
  
  // Generate ASCII art line by line
  const lines: string[] = Array(height).fill('')
  
  chars.forEach(char => {
    const charArt = font[char] || font[' ']
    for (let i = 0; i < height; i++) {
      lines[i] += charArt[i] + ' '
    }
  })

  return lines.join('\n')
}

// Component version
export default function ASCIIArtGenerator({ text, style = 'block' }: ASCIIArtGeneratorProps) {
  const asciiArt = generateASCIIArt(text, style)
  
  return (
    <div className="font-mono text-hacker-green text-xs leading-tight whitespace-pre" style={{ fontFamily: "'VT323', monospace" }}>
      {asciiArt}
    </div>
  )
}
